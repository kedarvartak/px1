package docs

import (
	"encoding/json"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// ManifestFile is the machine-readable list of pages the UI is built from.
const ManifestFile = Dir + "/manifest.json"

// Manifest is docs/manifest.json.
type Manifest struct {
	Version  int      `json:"version"`
	Sections []string `json:"sections"`
	Pages    []Page   `json:"pages"`
}

var sectionTitles = map[string]string{
	"start":      "Start",
	"guides":     "Guides",
	"concepts":   "Concepts",
	"reference":  "Reference",
	"operations": "Operations",
	"policies":   "Policies",
}

// Generated returns the files derived from the pages, keyed by path relative
// to the repository root: the manifest and the index.
func Generated(pages []Page) map[string]string {
	manifest := Manifest{Version: 1, Sections: Sections, Pages: pages}
	if manifest.Pages == nil {
		manifest.Pages = []Page{}
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		panic(err) // Page holds only strings and string slices
	}
	return map[string]string{
		ManifestFile:          string(data) + "\n",
		Dir + "/" + IndexFile: renderIndex(pages),
	}
}

// renderIndex lists every page by section, so no page is unreachable.
func renderIndex(pages []Page) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `px1 docs manifest` from the front matter of each page. Do not edit. -->\n\n")
	b.WriteString("# px1 documentation\n\n")
	b.WriteString("Each page states a status: **shipped** (usable now), **built** (code and tests exist, not deployed) or **planned**.\n")
	for _, section := range Sections {
		wrote := false
		for _, page := range pages {
			if page.Section != section {
				continue
			}
			if !wrote {
				fmt.Fprintf(&b, "\n## %s\n\n", sectionTitles[section])
				wrote = true
			}
			fmt.Fprintf(&b, "- [%s](%s) (%s)\n", page.Title, path.Base(page.Path), page.Status)
		}
	}
	return b.String()
}

// WriteGenerated writes the manifest and the index and returns the paths it
// changed.
func WriteGenerated(root string) ([]string, error) {
	pages, problems, err := LoadPages(root)
	if err != nil {
		return nil, err
	}
	if len(problems) > 0 {
		return nil, fmt.Errorf("%s (and %d more): fix the front matter first", problems[0], len(problems)-1)
	}
	var changed []string
	for _, rel := range []string{ManifestFile, Dir + "/" + IndexFile} {
		want := Generated(pages)[rel]
		full := filepath.Join(root, filepath.FromSlash(rel))
		if got, err := os.ReadFile(full); err == nil && string(got) == want {
			continue
		}
		if err := os.WriteFile(full, []byte(want), 0o644); err != nil {
			return nil, err
		}
		changed = append(changed, rel)
	}
	return changed, nil
}
