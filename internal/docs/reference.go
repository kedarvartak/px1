package docs

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Generated reference pages, and pages that hold a generated region.
const (
	CLIReferenceFile  = Dir + "/CLI_REFERENCE.md"
	ActionInputsFile  = Dir + "/ACTION_INPUTS.md"
	findingSchemaFile = "schemas/finding.schema.json"
	findingSchemaPage = Dir + "/FINDING_SCHEMA.md"
	agentToolsPage    = Dir + "/AGENT_TOOLS.md"
)

const generatedNote = "<!-- Generated by `px1 docs gen` from the source files in `covers`. Do not edit. -->"

func readFile(path string) (string, error) {
	data, err := os.ReadFile(path)
	return string(data), err
}

// Reference returns the reference content derived from code, keyed by path
// relative to the repository root. A whole page is generated when its source
// exists; a region is filled only in a page that carries its markers.
func Reference(root string) (map[string]string, error) {
	out := map[string]string{}

	commands, err := Commands(root)
	if err != nil {
		return nil, err
	}
	if len(commands) > 0 {
		out[CLIReferenceFile] = renderCLI(commands)
	}

	actions, err := Actions(root)
	if err != nil {
		return nil, err
	}
	if len(actions) > 0 {
		out[ActionInputsFile] = renderActions(actions)
	}

	schema, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(findingSchemaFile)))
	if err == nil {
		fields, err := SchemaFields(schema)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", findingSchemaFile, err)
		}
		if err := fillRegion(root, out, findingSchemaPage, "finding-fields", fieldTable(fields)); err != nil {
			return nil, err
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return nil, err
	}

	tools, err := Tools(root)
	if err != nil {
		return nil, err
	}
	if len(tools) > 0 {
		if err := fillRegion(root, out, agentToolsPage, "agent-tools", toolTable(tools)); err != nil {
			return nil, err
		}
	}
	return out, nil
}

// fillRegion replaces the text between a page's region markers. A page that
// does not exist is skipped; a page without the markers is an error, because
// the facts would otherwise be silently missing from it.
func fillRegion(root string, out map[string]string, rel, name, content string) error {
	text, err := readFile(filepath.Join(root, filepath.FromSlash(rel)))
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	start := "<!-- px1:generated " + name + " -->"
	end := "<!-- px1:end " + name + " -->"
	i := strings.Index(text, start)
	j := strings.Index(text, end)
	if i < 0 || j < i {
		return fmt.Errorf("%s: missing the %q and %q markers", rel, start, end)
	}
	out[rel] = text[:i+len(start)] + "\n" + content + text[j:]
	return nil
}

func frontMatter(title string, covers []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "---\ntitle: %s\nsection: reference\nkind: reference\nstatus: shipped\ncovers:\n", title)
	for _, entry := range covers {
		fmt.Fprintf(&b, "  - %s\n", entry)
	}
	b.WriteString("verified_at:\n---\n\n" + generatedNote + "\n\n")
	return b.String()
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "<", "\\<") // "<out>" would be dropped as an HTML tag
	return strings.Join(strings.Fields(s), " ")
}

func renderCLI(commands []Command) string {
	seen := map[string]bool{"main.go": true}
	for _, command := range commands {
		for _, file := range command.Files {
			seen[file] = true
		}
	}
	var covers []string
	for file := range seen {
		covers = append(covers, file)
	}
	sort.Strings(covers)

	var b strings.Builder
	b.WriteString(frontMatter("Command-line reference", covers))
	b.WriteString("# Command-line reference\n\nEvery `px1` subcommand and its flags, read from the source.\n\n")
	for _, command := range commands {
		fmt.Fprintf(&b, "- [`px1 %s`](#px1-%s)\n", command.Name, command.Name)
	}
	for _, command := range commands {
		fmt.Fprintf(&b, "\n## px1 %s\n\n", command.Name)
		if command.Summary != "" {
			b.WriteString(command.Summary + "\n\n")
		}
		if len(command.Flags) == 0 {
			b.WriteString("This command takes no flags.\n")
			continue
		}
		b.WriteString("| Flag | Type | Default | Description |\n| --- | --- | --- | --- |\n")
		for _, f := range command.Flags {
			fmt.Fprintf(&b, "| `--%s` | %s | %s | %s |\n", f.Name, f.Type, cell(f.Default), cell(f.Usage))
		}
	}
	return b.String()
}

func renderActions(actions []Action) string {
	var covers []string
	for _, action := range actions {
		covers = append(covers, action.Path)
	}
	var b strings.Builder
	b.WriteString(frontMatter("Action inputs", covers))
	b.WriteString("# Action inputs\n\nThe inputs of each GitHub Action in this repository, read from its `action.yml`.\n")
	for _, action := range actions {
		fmt.Fprintf(&b, "\n## %s\n\n`%s`\n\n%s\n\n", action.Name, action.Path, action.Description)
		if len(action.Inputs) == 0 {
			b.WriteString("This action takes no inputs.\n")
			continue
		}
		b.WriteString("| Input | Required | Default | Description |\n| --- | --- | --- | --- |\n")
		for _, input := range action.Inputs {
			required, def := "no", ""
			if input.Required {
				required = "yes"
			}
			if input.Default != "" {
				def = "`" + input.Default + "`"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", input.Name, required, cell(def), cell(input.Description))
		}
	}
	return b.String()
}

func fieldTable(fields []Field) string {
	var b strings.Builder
	b.WriteString("\n| Field | Type | Required | Constraints |\n| --- | --- | --- | --- |\n")
	for _, f := range fields {
		required := "no"
		if f.Required {
			required = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", f.Name, f.Type, required, cell(f.Constraints))
	}
	b.WriteString("\n")
	return b.String()
}

func toolTable(tools []Tool) string {
	var b strings.Builder
	b.WriteString("\n| Tool | What the model is told | Arguments |\n| --- | --- | --- |\n")
	for _, tool := range tools {
		var args []string
		for _, f := range tool.Arguments {
			arg := "`" + f.Name + "`"
			if !f.Required {
				arg += " (optional)"
			}
			args = append(args, arg)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", tool.Name, cell(tool.Description), strings.Join(args, ", "))
	}
	b.WriteString("\n")
	return b.String()
}
